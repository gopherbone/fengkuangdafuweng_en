def parse():
    glyphs = {}
    lines = RAW.strip('\n').split('\n')
    i = 0
    while i < len(lines):
        head = lines[i]
        assert head.startswith('[') and head.endswith(']') and len(head) == 3, head
        ch = head[1]
        rows = lines[i + 1:i + 13]
        w = len(rows[0])
        assert all(len(r) == w for r in rows), (ch, rows)
        glyphs[ch] = [int(r.replace('#', '1').replace('.', '0'), 2) << (8 - w) for r in rows], w
        i += 13
    return glyphs

GLYPHS = parse()
# space is narrower than its 3 px drawing suggests: 3 px + 1 spacing = 4 px gap
if __name__ == '__main__':
    print(len(GLYPHS), 'glyphs', sorted(GLYPHS))
